/**
 * Полупрозрачный оттенок цвета для фона и рамок.
 *
 * Нужна потому, что привычное `color + '2e'` работает только с
 * литеральным hex. Цвета темы заданы переменными, и `var(--x)2e`
 * не склеивается: CSS подставляет значение переменной как отдельный
 * токен, выражение становится невалидным и свойство молча
 * отбрасывается — фон не рисуется, а ошибки нигде не видно.
 */
export function tint(color: string, percent: number): string {
  return `color-mix(in srgb, ${color} ${percent}%, transparent)`
}
