// Текст статьи без markdown-разметки: по нему идёт поиск справки и режутся фрагменты результатов.

/** Тело статьи простым текстом: без заголовков, выделения, кода, ссылок и разметки таблиц и списков. */
export function plainText(body: string): string {
  return body
    .replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '') // остаток фронтматтера, если попал в тело
    .replace(/^```.*$/gm, '') // ограды кода: сам код остаётся
    .replace(/^\s*\|?[\s:|-]*-[\s:|-]*\|?\s*$/gm, '') // строка-разделитель таблицы |---|:--|
    .replace(/^\s{0,3}#{1,6}\s+/gm, '') // заголовки
    .replace(/^\s*>\s?/gm, '') // цитаты
    .replace(/^\s*(?:[-*+]|\d+\.)\s+/gm, '') // маркеры списков
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1') // [текст](адрес) → текст
    .replace(/(\*\*|__)(.+?)\1/g, '$2') // **жирный**
    .replace(/([*_])(.+?)\1/g, '$2') // *курсив*
    .replace(/`([^`]*)`/g, '$1') // `код`
    .replace(/\|/g, ' ') // границы ячеек таблицы
    .replace(/\s+/g, ' ')
    .trim()
}
