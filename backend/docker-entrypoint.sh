#!/bin/sh
# Схема приводится к текущей до старта приложения.
#
# Без этого шага сервис поднимается «успешно» и падает на первом же
# запросе к пустой базе — самая неприятная разновидность поломки,
# потому что логи старта при этом чистые.
set -e

echo "применяю миграции..."
alembic upgrade head

echo "запускаю приложение..."
# exec: uvicorn становится процессом 1 и получает сигналы остановки
# напрямую, иначе docker stop будет ждать таймаута и убивать по SIGKILL.
exec "$@"
